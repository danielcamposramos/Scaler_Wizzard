class DatasetCurator:
    """Curates and filters datasets for specific TRMC capabilities."""

    def __init__(self, cache_dir: Optional[str] = None):
        self.cache_dir = cache_dir

    def ingest_hf_dataset(self, path: str, split: str = "train", limit: Optional[int] = None, name: Optional[str] = None):
        """
        Loads a dataset from Hugging Face and applies standard Scaler Wizard formatting.
        """
        print(f"🌐 [HF-HUB] Fetching REAL dataset: {path} (config: {name or 'default'})")
        try:
            split_str = f"{split}[:{limit}]" if limit else split
            dataset = load_dataset(path, name=name, split=split_str, cache_dir=self.cache_dir)
            return dataset
        except Exception as e:
            print(f"Error loading dataset {path}: {e}")
            return None

